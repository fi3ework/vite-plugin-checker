export interface NormalizedDiagnostic {
  /** error message */
  message?: string
  /** rule that reported the diagnostic, as it appears in `message` */
  rule?: string
  /** documentation URL for `rule` */
  ruleUrl?: string
  /** error conclusion */
  conclusion?: string
  /** error stack */
  stack?: string | string[]
  /** file name */
  id?: string
  /** checker diagnostic source */
  checker: string
  /** raw code frame generated by @babel/code-frame */
  codeFrame?: string
  /** code frame, but striped */
  stripedCodeFrame?: string
  /** error code location */
  loc?: SourceLocation
  /** error level */
  level?: DiagnosticLevel
}

const defaultLogLevel = [
  DiagnosticLevel.Warning,
  DiagnosticLevel.Error,
  DiagnosticLevel.Suggestion,
  DiagnosticLevel.Message,
]

export function filterLogLevel(
  diagnostics: NormalizedDiagnostic,
  level?: DiagnosticLevel[],
): NormalizedDiagnostic | null
export function filterLogLevel(
  diagnostics: NormalizedDiagnostic[],
  level?: DiagnosticLevel[],
): NormalizedDiagnostic[]
export function filterLogLevel(
  diagnostics: NormalizedDiagnostic | NormalizedDiagnostic[],
  level: DiagnosticLevel[] = defaultLogLevel,
): NormalizedDiagnostic | null | NormalizedDiagnostic[] {
  if (Array.isArray(diagnostics)) {
    return diagnostics.filter((d) => {
      if (typeof d.level !== 'number') return false
      return level.includes(d.level)
    })
  }
  if (!diagnostics.level) return null
  return level.includes(diagnostics.level) ? diagnostics : null
}

let terminalHyperlinks = false

/**
 * Whether file paths in terminal logs are emitted as OSC 8 hyperlinks. Set from
 * the main thread, as worker threads have no real TTY to detect support from.
 */
export function setTerminalHyperlinks(enabled: boolean) {
  terminalHyperlinks = enabled
}

function formatTerminalFile(file: string, loc?: SourceLocation): string {
  const line = loc?.start.line
  const column = loc?.start.column || undefined
  const position = line
    ? `:${colorize('yellow', String(line))}${column ? `:${colorize('yellow', String(column))}` : ''}`
    : ''

  if (!path.isAbsolute(file)) return file + position

  return link(file, {
    line,
    column,
    enabled: terminalHyperlinks,
    formatter: (absolute) => path.relative(process.cwd(), absolute) + position,
  })
}

function formatTerminalMessage({
  message,
  rule,
  ruleUrl,
}: NormalizedDiagnostic): string | undefined {
  if (!message || !rule || !ruleUrl) return message
  const index = message.lastIndexOf(rule)
  if (index === -1) return message

  return (
    message.slice(0, index) +
    hyperlink(rule, ruleUrl, { enabled: terminalHyperlinks }) +
    message.slice(index + rule.length)
  )
}

export function diagnosticToTerminalLog(
  d: NormalizedDiagnostic,
  name?:
    | 'TypeScript'
    | 'vue-tsc'
    | 'ESLint'
    | 'Stylelint'
    | 'Biome'
    | 'oxlint'
    | 'svelte-check',
): string {
  const nameInLabel = name ? `(${name})` : ''
  const labelMap: Record<DiagnosticLevel, string> = {
    [DiagnosticLevel.Error]: colorize(
      ['bold', 'black', 'bgRedBright'],
      ` ERROR${nameInLabel} `,
    ),
    [DiagnosticLevel.Warning]: colorize(
      ['bold', 'black', 'bgYellowBright'],
      ` WARNING${nameInLabel} `,
    ),
    [DiagnosticLevel.Suggestion]: colorize(
      ['bold', 'black', 'bgBlueBright'],
      ` SUGGESTION${nameInLabel} `,
    ),
    [DiagnosticLevel.Message]: colorize(
      ['bold', 'black', 'bgCyanBright'],
      ` MESSAGE${nameInLabel} `,
    ),
  }

  const levelLabel = labelMap[d.level ?? DiagnosticLevel.Error]
  const fileLabel = `${colorize(['bold', 'black', 'bgCyanBright'], ' FILE ')} `

  return [
    `${levelLabel} ${formatTerminalMessage(d)}`,
    d.id && `${fileLabel}${formatTerminalFile(d.id, d.loc)}${os.EOL}`,
    d.codeFrame + os.EOL,
    d.conclusion,
  ]
    .filter(Boolean)
    .join(os.EOL)
}

export function diagnosticToConsoleLevel(d: NormalizedDiagnostic) {
  if (!d) return 'error'
  if (d.level === DiagnosticLevel.Message) return 'info'
  if (d.level === DiagnosticLevel.Suggestion) return 'info'
  if (d.level === DiagnosticLevel.Warning) return 'warn'
  return 'error'
}

export function diagnosticToRuntimeError(
  d: NormalizedDiagnostic,
): DiagnosticToRuntime
export function diagnosticToRuntimeError(
  d: NormalizedDiagnostic[],
): DiagnosticToRuntime[]
export function diagnosticToRuntimeError(
  diagnostics: NormalizedDiagnostic | NormalizedDiagnostic[],
): DiagnosticToRuntime | DiagnosticToRuntime[] {
  const diagnosticsArray = Array.isArray(diagnostics)
    ? diagnostics
    : [diagnostics]

  const results: DiagnosticToRuntime[] = diagnosticsArray.map((d) => {
    let loc: DiagnosticToRuntime['loc']
    if (d.loc) {
      loc = {
        file: d.id ?? '',
        line: d.loc.start.line,
        column: typeof d.loc.start.column === 'number' ? d.loc.start.column : 0,
      }
    }

    return {
      message: d.message ?? '',
      stack:
        typeof d.stack === 'string'
          ? d.stack
          : Array.isArray(d.stack)
            ? d.stack.join(os.EOL)
            : '',
      id: d.id,
      frame: d.stripedCodeFrame,
      checkerId: d.checker,
      level: d.level,
      loc,
      rule: d.rule,
      ruleUrl: d.ruleUrl,
    }
  })

  return Array.isArray(diagnostics) ? results : results[0]!
}

export function toClientPayload(
  id: string,
  diagnostics: DiagnosticToRuntime[],
): ClientDiagnosticPayload {
  return {
    event: WS_CHECKER_ERROR_EVENT,
    data: {
      checkerId: id,
      diagnostics,
    },
  }
}

export function withOverlayFileLinks(
  payload: ClientDiagnosticPayload,
  root: string,
  editorUrl?: (location: EditorLocation) => string | undefined,
): ClientDiagnosticPayload {
  return {
    ...payload,
    data: {
      ...payload.data,
      diagnostics: payload.data.diagnostics.map((d) => {
        const file = (d.loc?.file || d.id)?.split('?')[0]
        if (!file || !path.isAbsolute(file)) return d

        return {
          ...d,
          relativeFile: path.relative(root, file).split(path.sep).join('/'),
          editorUrl: editorUrl?.({
            file,
            line: d.loc?.line || 1,
            column: d.loc?.column || 1,
          }),
        }
      }),
    },
  }
}

export function wrapCheckerSummary(
  checkerName: string,
  rawSummary: string,
): string {
  return `[${checkerName}] ${rawSummary}`
}

export function composeCheckerSummary(
  checkerName: string,
  errorCount: number,
  warningCount: number,
): string {
  const message = `Found ${errorCount} error${
    errorCount === 1 ? '' : 's'
  } and ${warningCount} warning${warningCount === 1 ? '' : 's'}`

  const hasError = errorCount > 0
  const hasWarning = warningCount > 0
  const color = hasError ? 'red' : hasWarning ? 'yellow' : 'green'
  return colorize(color, wrapCheckerSummary(checkerName, message))
}

/* ------------------------------- TypeScript ------------------------------- */

export function normalizeTsDiagnostic(d: TsDiagnostic): NormalizedDiagnostic {
  const fileName = d.file?.fileName
  const {
    flattenDiagnosticMessageText,
  }: {
    flattenDiagnosticMessageText: typeof flattenDiagnosticMessageTextType
  } = _require('typescript')

  const message = flattenDiagnosticMessageText(d.messageText, os.EOL)

  let loc: SourceLocation | undefined
  const pos =
    d.start === undefined
      ? null
      : d.file?.getLineAndCharacterOfPosition?.(d.start)
  if (
    pos &&
    d.file &&
    typeof d.start === 'number' &&
    typeof d.length === 'number'
  ) {
    loc = tsLikeLocToBabelLoc({
      start: pos,
      end: d.file.getLineAndCharacterOfPosition(d.start + d.length),
    })
  }

  let codeFrame: string | undefined
  if (loc) {
    codeFrame = createFrame(d.file!.text, loc)
  }

  return {
    message,
    conclusion: '',
    codeFrame,
    stripedCodeFrame: codeFrame && strip(codeFrame),
    id: fileName,
    checker: 'TypeScript',
    loc,
    level: d.category as any as DiagnosticLevel,
  }
}

/* --------------------------------- vue-tsc -------------------------------- */

export function normalizeVueTscDiagnostic(
  d: TsDiagnostic,
): NormalizedDiagnostic {
  const diagnostic = normalizeTsDiagnostic(d)
  diagnostic.checker = 'vue-tsc'
  return diagnostic
}

/* --------------------------------- ESLint --------------------------------- */

const isNormalizedDiagnostic = (
  d: NormalizedDiagnostic | null | undefined,
): d is NormalizedDiagnostic => {
  return Boolean(d)
}

export function normalizeEslintDiagnostic(
  diagnostic: ESLint.LintResult,
  rulesMeta?: ReturnType<ESLint['getRulesMetaForResults']>,
): NormalizedDiagnostic[] {
  return diagnostic.messages
    .map((d) => {
      let level = DiagnosticLevel.Error
      switch (d.severity as number) {
        case 0: // off, ignore this
          level = DiagnosticLevel.Error
          return null
        case 1: // warn
          level = DiagnosticLevel.Warning
          break
        case 2: // error
          level = DiagnosticLevel.Error
          break
      }

      const loc = lineColLocToBabelLoc(d)

      const codeFrame = createFrame(diagnostic.source ?? '', loc)

      return {
        message: `${d.message} (${d.ruleId})`,
        rule: d.ruleId ?? undefined,
        ruleUrl: d.ruleId ? rulesMeta?.[d.ruleId]?.docs?.url : undefined,
        conclusion: '',
        codeFrame,
        stripedCodeFrame: codeFrame && strip(codeFrame),
        id: diagnostic.filePath,
        checker: 'ESLint',
        loc,
        level,
      } as any as NormalizedDiagnostic
    })
    .filter(isNormalizedDiagnostic)
}

/* --------------------------------- Stylelint --------------------------------- */

export function normalizeStylelintDiagnostic(
  diagnostic: Stylelint.LintResult,
  ruleMetadata?: Stylelint.LinterResult['ruleMetadata'],
): NormalizedDiagnostic[] {
  return diagnostic.warnings
    .map((d) => {
      let level = DiagnosticLevel.Error
      switch (d.severity) {
        case 'warning': // warn
          level = DiagnosticLevel.Warning
          break
        case 'error': // error
          level = DiagnosticLevel.Error
          break
        default:
          level = DiagnosticLevel.Error
          return null
      }

      const loc = lineColLocToBabelLoc(d)

      const codeFrame = createFrame(diagnostic._postcssResult?.css ?? '', loc)

      return {
        message: d.text.endsWith(`(${d.rule})`)
          ? d.text
          : `${d.text} (${d.rule})`,
        rule: d.rule,
        ruleUrl: d.url ?? ruleMetadata?.[d.rule]?.url,
        conclusion: '',
        codeFrame,
        stripedCodeFrame: codeFrame && strip(codeFrame),
        id: diagnostic.source,
        checker: 'Stylelint',
        loc,
        level,
      } as any as NormalizedDiagnostic
    })
    .filter(isNormalizedDiagnostic)
}

/* ------------------------------ miscellaneous ----------------------------- */
export function ensureCall(callback: CallableFunction) {
  setTimeout(() => {
    callback()
  })
}

export function consoleLog(value: string, level: 'info' | 'warn' | 'error') {
  if (isMainThread) {
    console[level](value)
  } else {
    parentPort?.postMessage({
      type: ACTION_TYPES.console,
      level: level,
      payload: value,
    })
  }
}
